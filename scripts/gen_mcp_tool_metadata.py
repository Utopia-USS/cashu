"""Generate retained native MCP tool schemas from the frozen Python registry, without a database.

The TypeScript-owned specs are excluded; this file supplies schemas reused by native tool handlers.
"""

from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path

from cashu.core.mcp.registry import all_tools

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "packages/mcp/src/runtime/toolSchemas.generated.ts"
NATIVE = {
    "profile_overview",
    "setup_status",
    "networth_breakdown",
    "mark_review_done",
    "spending_breakdown",
    "cashflow_summary",
    "recurring_payments",
    "uncategorized_merchants",
    "set_merchant_category",
    "validate_budget_import",
    "loans_summary",
}
INVESTMENT_READS = {
    "portfolio_overview",
    "positions",
    "signals",
    "review_context",
    "strategy_status",
    "history_metrics",
    "theses",
    "inspect_export",
    "validate_import",
}


def render() -> str:
    rows = [
        {
            "name": tool.name,
            "module": tool.module,
            "description": tool.description,
            "properties": tool.properties,
            "required": list(tool.required),
            "write": tool.write,
            "refused": tool.refused,
            "refusedValues": tool.refused_values,
            "nullable": list(tool.nullable),
            "also": list(tool.also),
        }
        for tool in all_tools().values()
        if tool.name not in NATIVE
    ]
    # JSON is valid TypeScript. The normal repository formatter owns the generated layout.
    body = json.dumps(
        [row for row in rows if row["name"] not in INVESTMENT_READS], ensure_ascii=False, indent=2
    )
    investments = json.dumps(
        [row for row in rows if row["name"] in INVESTMENT_READS], ensure_ascii=False, indent=2
    )
    return (
        "// Generated by scripts/gen_mcp_tool_metadata.py from the frozen Python tool registry.\n"
        "// Native tool implementations retain these schema contracts for parity with the source app.\n"
        'import type { ToolMetadata } from "../registry.js";\n\n'
        f"export const TOOL_ORDER: readonly string[] = {json.dumps(list(all_tools()))};\n\n"
        f"export const NATIVE_TOOL_SCHEMAS: readonly ToolMetadata[] = {body};\n"
        f"export const INVESTMENT_READ_TOOLS: readonly ToolMetadata[] = {investments};\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    formatted = subprocess.run(
        ["pnpm", "exec", "biome", "format", "--stdin-file-path", str(OUTPUT)],
        input=render(),
        text=True,
        capture_output=True,
        check=True,
        cwd=ROOT,
    ).stdout
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != formatted:
            raise SystemExit("Native MCP tool schemas are stale; run this generator without --check.")
        print("Native MCP tool schemas are current.")
        return
    OUTPUT.write_text(formatted, encoding="utf-8")
    print("Generated native MCP tool schemas (no profile data read).")


if __name__ == "__main__":
    main()
