"""Generate the delegated MCP registry contract from Python code, without opening a database.

TRANSITIONAL(S38f): remove this generator and its catalog once every tool is native.
Native tools are deliberately excluded: their TypeScript specs own their metadata.
"""

from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path

from cashu.core.mcp.registry import all_tools

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "packages/mcp/src/runtime/delegated.generated.ts"
NATIVE = {
    "profile_overview", "setup_status", "networth_breakdown", "mark_review_done",
    "spending_breakdown", "cashflow_summary", "recurring_payments",
    "uncategorized_merchants", "validate_budget_import", "loans_summary",
}


def render() -> str:
    rows = [
        {
            "name": tool.name,
            "module": tool.module,
            "description": tool.description,
            "properties": tool.properties,
            "required": list(tool.required),
            "write": tool.write,
            "refused": tool.refused,
            "refusedValues": tool.refused_values,
            "nullable": list(tool.nullable),
            "also": list(tool.also),
        }
        for tool in all_tools().values()
        if tool.name not in NATIVE
    ]
    # JSON is valid TypeScript. The normal repository formatter owns the generated layout.
    body = json.dumps(rows, ensure_ascii=False, indent=2)
    return (
        "// Generated by scripts/gen_mcp_tool_metadata.py from the Python tool registry.\n"
        "// TRANSITIONAL(S38f): delegated contracts disappear as their native specs replace them.\n"
        'import type { ToolMetadata } from "../registry.js";\n\n'
        f"export const TOOL_ORDER: readonly string[] = {json.dumps(list(all_tools()))};\n\n"
        f"export const DELEGATED_TOOLS: readonly ToolMetadata[] = {body};\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    formatted = subprocess.run(
        ["pnpm", "exec", "biome", "format", "--stdin-file-path", str(OUTPUT)],
        input=render(),
        text=True,
        capture_output=True,
        check=True,
        cwd=ROOT,
    ).stdout
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != formatted:
            raise SystemExit("Delegated MCP metadata is stale; run this generator without --check.")
        print("Delegated MCP metadata is current.")
        return
    OUTPUT.write_text(formatted, encoding="utf-8")
    print("Generated delegated MCP metadata (no profile data read).")


if __name__ == "__main__":
    main()
