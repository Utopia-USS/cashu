/// <reference types="node" />
/**
 * The expected text of `src/investments/strategy/templates.data.ts`, built from the Python app's
 * template folder (used by the generator and `templates.test.ts`; the domain never reads files).
 */

import { readdirSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/** The Python app's strategy template folder, relative to the repo root. */
export const TEMPLATE_SOURCE_DIR = "src/cashu/modules/investments/templates/strategy";

const folder = fileURLToPath(new URL(`../../../${TEMPLATE_SOURCE_DIR}/`, import.meta.url));

/** File name -> text of every `.yaml` / `.md` file of the folder, sorted by name. */
export function templateFiles(): ReadonlyMap<string, string> {
  const names = readdirSync(folder)
    .filter((name) => name.endsWith(".yaml") || name.endsWith(".md"))
    .sort();
  return new Map(names.map((name) => [name, readFileSync(`${folder}${name}`, "utf8")]));
}

/** `text` as the body of a template literal (backslash, backtick and `${` escaped). */
function templateLiteral(text: string): string {
  return text.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");
}

export function strategyTemplatesSource(): string {
  const entries = [...templateFiles()]
    .map(([name, text]) => `  ${JSON.stringify(name)}: \`${templateLiteral(text)}\`,`)
    .join("\n");
  return `// Generated by \`pnpm --filter @cashu/domain gen:strategy-templates\` from ${TEMPLATE_SOURCE_DIR}; do not edit.

/** File name -> text of the shipped strategy templates and the strategy.yaml reference (README.md). */
export const STRATEGY_TEMPLATE_FILES: Readonly<Record<string, string>> = {
${entries}
};
`;
}
