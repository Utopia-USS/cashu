"""``cashu serve --parent-pipe``: the server is owned by a parent process (the desktop shell).

stdin is a pipe from the parent, and it carries the whole contract:

- The first line is the per-launch API token, generated by the parent. The parent therefore knows
  the token without reading the server's output, and the token never reaches stdout, a log, the
  environment of the server's own children or ``<data dir>/api-token`` (the server does not write
  that file in this mode, like the in-process desktop window, ``desktop/shell.py``).
- The parent keeps its end open for as long as it wants the server. End of file means the parent
  exited or died: the kernel closes the pipe for a SIGKILLed process too, so this works where a
  parent-death signal does not exist (macOS has no ``PR_SET_PDEATHSIG``) and needs no pid polling.
  The server then stops: gracefully first (SIGTERM to itself, uvicorn drains), hard after
  :data:`STOP_GRACE` seconds, so an orphan never keeps serving the data dir.
"""

from __future__ import annotations

import os
import re
import signal
import threading
from collections.abc import Callable
from typing import BinaryIO

# Same alphabet as ``security.generate_token`` (URL-safe base64), long enough to be a real secret.
TOKEN_PATTERN = re.compile(r"[A-Za-z0-9_-]{32,256}")
MAX_LINE = 512
STOP_GRACE = 10.0


class ParentPipeError(ValueError):
    """The parent did not send a usable token (message safe to show)."""


def read_token(stream: BinaryIO) -> str:
    """The first line of the pipe: the API token the parent generated."""
    line = stream.readline(MAX_LINE)
    if not line:
        raise ParentPipeError("--parent-pipe: stdin closed before the parent sent the API token")
    if not line.endswith(b"\n"):
        raise ParentPipeError("--parent-pipe: the first line of stdin must be the API token")
    token = line.strip().decode("ascii", errors="replace")
    if not TOKEN_PATTERN.fullmatch(token):
        raise ParentPipeError(
            "--parent-pipe: the API token must be 32-256 URL-safe base64 characters"
        )
    return token


def watch(stream: BinaryIO, on_parent_gone: Callable[[], None]) -> threading.Thread:
    """Calls ``on_parent_gone`` (once, from a daemon thread) when the pipe reaches end of file.
    Anything else the parent writes is ignored."""

    def run() -> None:
        try:
            while stream.read(4096):
                pass
        except (OSError, ValueError):  # the pipe broke or was closed: the parent is gone as well
            pass
        on_parent_gone()

    thread = threading.Thread(target=run, name="cashu-parent-pipe", daemon=True)
    thread.start()
    return thread


def stop_process(
    grace: float = STOP_GRACE,
    *,
    kill: Callable[[int, int], None] = os.kill,
    hard_exit: Callable[[int], None] = os._exit,
) -> threading.Timer:
    """SIGTERM to this process (uvicorn's handler shuts the server down and the ``finally`` blocks
    run); if the process is still alive after ``grace`` seconds, exit hard."""
    timer = threading.Timer(grace, hard_exit, args=(1,))
    timer.daemon = True
    timer.start()
    kill(os.getpid(), signal.SIGTERM)
    return timer
