// The native helpers of one build flavor: CashUNotifications.node and CashUHostService.node (the
// flavor's bundle ID, host agent label and plist as clang string defines) and cashu-host-agent (the
// flavor's bundle ID and default data dir name in a generated CashUFlavor.swift).
//
//   node apps/desktop/scripts/build-native.mjs [<out dir in the flavor's build dir>] [arm64|x64] [prod|staging]
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildDirOf, flavorById } from "./flavor.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const flavor = flavorById(process.argv[4] ?? "prod");
const out = resolve(process.argv[2] ?? join(buildDirOf(flavor), "resources"));
const arch = process.argv[3] ?? process.arch;
if (!out.startsWith(`${buildDirOf(flavor)}/`))
  throw new Error(`Output must be in ${flavor.buildDir}`);
if (arch !== "arm64" && arch !== "x64") throw new Error("Expected arm64 or x64");
const plain = /^[A-Za-z0-9 ._-]+$/;
for (const value of [flavor.bundleId, flavor.hostAgentLabel, flavor.dataDirName.darwin])
  if (!plain.test(value)) throw new Error(`Unexpected flavor value ${value}`);
const defines = [
  `-DCASHU_BUNDLE_ID="${flavor.bundleId}"`,
  `-DCASHU_HOST_AGENT_LABEL="${flavor.hostAgentLabel}"`,
  `-DCASHU_HOST_AGENT_PLIST="${flavor.hostAgentLabel}.plist"`,
];
const clang = execFileSync("xcrun", ["--find", "clang++"], { encoding: "utf8" }).trim();
const sdk = execFileSync("xcrun", ["--sdk", "macosx", "--show-sdk-path"], {
  encoding: "utf8",
}).trim();
const swift = execFileSync("xcrun", ["--find", "swiftc"], { encoding: "utf8" }).trim();
const node = execFileSync("node", ["-p", "process.execPath"], { encoding: "utf8" }).trim();
const include = resolve(dirname(node), "../include/node");
const clangArch = arch === "x64" ? "x86_64" : "arm64";
const native = join(out, "native");
mkdirSync(native, { recursive: true });
for (const [name, frameworks] of [
  ["CashUNotifications", ["Foundation", "UserNotifications", "CoreFoundation"]],
  ["CashUHostService", ["Foundation", "ServiceManagement"]],
]) {
  execFileSync(
    clang,
    [
      "-std=c++17",
      "-fobjc-arc",
      "-x",
      "objective-c++",
      "-dynamiclib",
      "-arch",
      clangArch,
      "-isysroot",
      sdk,
      "-mmacosx-version-min=13.0",
      "-I",
      include,
      "-undefined",
      "dynamic_lookup",
      ...defines,
      ...frameworks.flatMap((framework) => ["-framework", framework]),
      join(root, "apps", "desktop", "native", `${name}.mm`),
      "-o",
      join(native, `${name}.node`),
    ],
    { stdio: "inherit" },
  );
}
// Swift has no string defines: the agent is compiled as main.swift beside a generated CashUFlavor.
const agentSource = join(out, "..", `agent-src-${arch}`);
rmSync(agentSource, { recursive: true, force: true });
mkdirSync(agentSource, { recursive: true });
copyFileSync(
  join(root, "apps", "desktop", "service", "CashUHostAgent.swift"),
  join(agentSource, "main.swift"),
);
writeFileSync(
  join(agentSource, "CashUFlavor.swift"),
  `// Generated by apps/desktop/scripts/build-native.mjs from packages/node-host/src/flavor.json (${flavor.id}).
enum CashUFlavor {
    static let bundleID = ${JSON.stringify(flavor.bundleId)}
    static let hostAgentLabel = ${JSON.stringify(flavor.hostAgentLabel)}
    static let hostAgentPlist = ${JSON.stringify(`${flavor.hostAgentLabel}.plist`)}
    static let dataDirName = ${JSON.stringify(flavor.dataDirName.darwin)}
}
`,
);
execFileSync(
  swift,
  [
    "-target",
    `${clangArch}-apple-macosx13.0`,
    "-sdk",
    sdk,
    "-O",
    join(agentSource, "main.swift"),
    join(agentSource, "CashUFlavor.swift"),
    "-o",
    join(out, "cashu-host-agent"),
  ],
  { stdio: "inherit" },
);
rmSync(agentSource, { recursive: true, force: true });
