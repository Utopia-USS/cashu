/** The app icon: the committed one, or the committed one with the flavor's badge (generated). */
function flavorIcon() {
  if (flavor.iconBadge === null) return null;
  const work = join(build, "icon");
  rmSync(work, { recursive: true, force: true });
  const iconset = join(work, `${flavor.id}.iconset`);
  mkdirSync(iconset, { recursive: true });
  const png = join(work, `${flavor.id}-1024.png`);
  run("swift", [
    join(root, "packaging/icon/make_flavor_icon.swift"),
    join(root, "packaging/icon/cashu-1024.png"),
    flavor.iconBadge,
    png,
  ]);
  for (const size of [16, 32, 128, 256, 512]) {
    for (const [scale, suffix] of [
      [1, ""],
      [2, "@2x"],
    ])
      run("sips", [
        "-z",
        String(size * scale),
        String(size * scale),
        png,
        "--out",
        join(iconset, `icon_${size}x${size}${suffix}.png`),
      ]);
  }
  const icns = join(work, `${flavor.id}.icns`);
  run("iconutil", ["-c", "icns", iconset, "-o", icns]);
  return icns;
}
