// Builds cashU.app for one macOS architecture (arm64 or x64; never universal) and zips it.
//
//   node apps/desktop/scripts/package-macos.mjs <arm64|x64> [--flavor prod|staging] [--dmg] [--reuse-desktop] [--out <dir>]
//        [--sign "Developer ID Application: <name> (<TEAMID>)" [--keychain <path>]
//          [--notarize <keychain-profile> | --notary-key <AuthKey.p8> --notary-key-id <id>
//           --notary-issuer <uuid>]]
//        [--test-build <json | @file> [--app-version <X.Y.Z>]]
//
// Default (dev, e2e, CI): ad hoc signature, artifacts in build/t46. Nothing is auto-discovered:
// without --sign no identity is used, and CSC_* / APPLE_* / notarization env is stripped.
//
// --flavor staging: the owner's local second app "cashU Staging" (packages/node-host/src/flavor.json:
// bundle ID io.utopiasoft.cashu.staging, its own data dir, workspaces, launch agent label, keychain
// services, URL scheme, MCP names, LAN port), built from the current checkout, ad hoc or, with --sign,
// Developer ID signed so the Keychain keeps trusting it across rebuilds (--notarize and --test-build are
// refused; it is never released), no app-update.yml (it never updates), an icon with the
// flavor's badge generated by packaging/icon/make_flavor_icon.swift. Everything lands in the flavor's
// own work dir: build/staging/electron-builder/mac-<arch>/cashU Staging.app and
// build/staging/cashU-Staging-<version>-mac-<arch>.zip. Never installed anywhere by this script.
//
// Release mode (--sign): this script is the only signer (electron-builder runs with identity null).
// Inside out, with the hardened runtime and a secure timestamp: every nested Mach-O file (Electron
// dylibs, crashpad, ShipIt, .node addons, cashu-host-agent), then the nested bundles (Electron
// frameworks, helper apps), then bundle-manifest.json (hashes Resources incl. app-update.yml), then
// the app. The team in --sign must equal RELEASE_TEAM_ID. Every codesign has a deadline: the key
// must be usable without a keychain dialog ("Always Allow" for codesign), checked before the build.
// Release entitlements (build/entitlements.release.mac.plist) go ONLY on the main executable and
// the four Electron helper apps: com.apple.security.cs.allow-jit, because V8 needs MAP_JIT pages
// under the hardened runtime in Electron main, the renderer, GPU (SwiftShader) and utility helpers
// and in the host (the cashU executable run with ELECTRON_RUN_AS_NODE); Chromium and
// @electron/osx-sign ship the same key there. Dropped on purpose: allow-unsigned-executable-memory
// (not needed with allow-jit since Electron 12), disable-library-validation (every library these
// processes load carries the same Team ID), device / personal-information keys (unused). Nested
// dylibs, chrome_crashpad_handler, ShipIt, the .node addons and cashu-host-agent get none. The ad
// hoc build keeps build/entitlements.mac.plist: ad hoc code has no Team ID, so library validation
// would refuse its own addons.
// --keychain: every codesign signs from that keychain (CI imports the Developer ID into a temporary
// one). Notarization credentials: --notarize names a notarytool keychain profile (the owner's Mac);
// --notary-key/--notary-key-id/--notary-issuer pass an App Store Connect API key (CI): the key file
// is handed to notarytool by path and never read or printed here; the key ID and issuer may print.
// With --notarize (or the API key): zip -> notarytool (wait) -> staple the app -> re-zip the stapled app; with --dmg
// also dmg from the stapled app -> sign -> notarize -> staple. The dmg holds the app and an
// `Applications -> /Applications` symlink (drag the app onto it to install or replace). Every notarization prints its
// submission id and status. Final checks: verify-package.mjs --release [--notarized] and spctl /
// stapler on the dmg. Artifacts in --out (relative to the current directory):
//   cashU-<version>-mac-arm64.{zip,dmg}, cashU-<version>-mac-x64.{zip,dmg}
// One latest-mac.yml can list both zips: electron-updater's MacUpdater picks the file whose name
// contains "arm64" on Apple silicon and drops those files on Intel. Separate arches (not
// universal): half the download, and native modules are built per arch.
//
// --test-build <marker>: a TEST BUILD for local update proofs. The marker (JSON or @file, rules in
// release-policy.mjs parseTestBuild: a http://127.0.0.1:<port>/ feed, an install root, a data dir)
// is sealed as Contents/Resources/test-build.json, listed in bundle-manifest.json, and app-update.yml
// names the local feed. verify-package.mjs --release (and so the release script) refuses such a
// bundle; the app honors the marker only from its verified bundle. --app-version overrides the
// version of a test build only (electron-builder extraMetadata), never package.json.
