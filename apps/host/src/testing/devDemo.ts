/** A seeding command: the synthetic queue path, or the durable native path of a native demo vault. */
async function apply<I, R>(vault: OpenVault, cmd: Command<I, R>, input: unknown): Promise<R> {
  if (vault.native === undefined) return command(vault, cmd, input);
  const result = await runHostVaultCommand(vault, cmd, input, `demo-${randomUUID()}`);
  if (result.kind !== "completed") throw new Error(`demo command ${result.kind}`);
  return result.value;
}

