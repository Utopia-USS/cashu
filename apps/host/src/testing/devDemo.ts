/** The demo profiles of an `init`ed data dir: profile slug -> vault id. */
export function devDemoProfiles(dataDir: string): ReadonlyMap<string, string> {
  return new Map(readMarker(dataDir).profiles.map((p) => [p.slug, p.vault]));
}

function readMarker(dataDir: string): Marker {
  const path = join(dataDir, MARKER);
  if (!existsSync(path)) throw new Error("not a dev demo data dir (run devDemo.ts init first)");
  const marker = JSON.parse(readFileSync(path, "utf8")) as Marker;
  if (marker.format !== 1 || !Array.isArray(marker.profiles))
    throw new Error("unreadable dev demo marker");
  return marker;
}

export interface ServedDevDemo {
  readonly host: LocalHost;
  /** Stops the host and releases the price cache. */
  stop(): Promise<void>;
}

/** Serves an `init`ed demo on its data dir's synthetic host (strategy files and price cache wired). */
export async function serveDevDemo(
  dataDir: string,
  options: {
    readonly home?: string;
    readonly labRoot?: string;
    /** A native demo's sync relay (the CLI binds it from the env; absent: no relay). */
    readonly relay?: HostRelayOptions;
  } = {},
): Promise<ServedDevDemo> {
  const home = options.home ?? homedir();
  const target = guardDataDir(dataDir, home);
  const marker = readMarker(target);
  if (marker.native) insideLab(target, labRoot(options.labRoot));
  const cachePath = join(target, DEV_DEMO_MARKET_DB);
  if (!existsSync(cachePath)) throw new Error("the dev demo price cache is absent");
  const driver = openNodeSqlite(cachePath);
  const prices = new investmentsLocal.SqlPriceCache(driver);
  let alive = true;
  const capabilities = new Map<string, StrategyScreenCapability>();
  try {
    for (const { slug, vault } of marker.profiles) {
      if (checkedProfileSlug(slug) === null) throw new Error("invalid demo profile segment");
      const path = join(target, "profiles", slug);
      mkdirSync(path, { recursive: true, mode: 0o700 });
      capabilities.set(
        vault,
        await syntheticStrategyDocuments({
          root: realpathSync(path),
          vault,
          generation: randomUUID(),
          isCurrent: () => alive,
        }),
      );
    }
  } catch (error) {
    driver.close();
    throw error;
  }
  const images = currentStrategyImages((vault, generation) => {
    const cap = capabilities.get(vault);
    return cap?.generation === generation && cap.isCurrent();
  });
  const currentVaultOf = (read: <R>(sql: string) => R[]) =>
    read<{ gid: string }>("SELECT gid FROM profiles")[0]?.gid;
  let host: LocalHost;
  try {
    host = await startLocalHost({
      dataDir: target,
      ...(marker.native
        ? {
            vaultSource: {
              kind: "native-production" as const,
              factory: new ProductionVaultSourceFactory(target, demoKeyStoreFactory(target)),
            },
            ...(options.relay === undefined ? {} : { relay: options.relay }),
          }
        : { vaultSource: { kind: "synthetic-harness" as const } }),
      home,
      build: BUILD,
      launcher: false,
      lingerMs: SERVE_LINGER_MS,
      strategyImages: images,
      strategies: { bind: (vault) => capabilities.get(vault) ?? null },
      investments: {
        strategy: images.source,
        market: {
          changes: prices,
          current: (read) => {
            const vault = currentVaultOf(read);
            return vault !== undefined && capabilities.get(vault)?.isCurrent() ? { prices } : null;
          },
          newestRateDate: () => prices.newestFxDate(),
        },
      },
      overview: {
        prices,
        changes: combinedChanges(prices, images.source.changes),
        sources: {
          plannedContribution: (read) => {
            const strategy = images.source.current(read);
            return strategy.status !== "current"
              ? null
              : budget.plannedContribution(strategy.state.state, strategy.state.config);
          },
          investmentRequest: (read, context) => {
            const vault = currentVaultOf(read);
            const strategy = images.source.current(read);
            if (vault === undefined || strategy.status !== "current" || context.prices === null)
              return null;
            return {
              vault: asProfileId(vault),
              asOf: context.today,
              lang: context.lang,
              strategy: strategy.state,
              prices: context.prices,
              forOwner: true,
              newestRateDate: prices.newestFxDate(),
              clock: {
                now: parseDateTime(new Date().toISOString()),
                today: context.today,
                timeZone: "Europe/Warsaw",
              },
            };
          },
        },
      },
    });
  } catch (error) {
    alive = false;
    driver.close();
    throw error;
  }
  try {
    for (const [vault, cap] of capabilities) {
      if (!host.stores.vaults.has(vault)) throw new Error("a demo vault is absent");
      images.publish({
        vault,
        generation: cap.generation,
        revision: randomUUID(),
        files: await readStrategyFiles(cap.files),
      });
    }
  } catch (error) {
    alive = false;
    await host.stop();
    driver.close();
    throw error;
  }
  let stopped: Promise<void> | undefined;
  return {
    host,
    stop() {
      stopped ??= (async () => {
        alive = false;
        await host.stop();
        driver.close();
      })();
      return stopped;
    },
  };
}

// ---------------------------------------------------------------------------------- entry

async function main(args: readonly string[]): Promise<void> {
  const [mode, dataDir, ...extra] = args;
  if (
    (mode !== "init" && mode !== "native" && mode !== "serve") ||
    dataDir === undefined ||
    extra.length !== 0
  ) {
    process.stderr.write("usage: devDemo.ts init|native|serve <data dir>\n");
    process.exit(64);
  }
  if (mode === "init") {
    await initDevDemo(dataDir);
    process.stdout.write(`dev demo created: ${HOUSEHOLDS.map((h) => h.slug).join(", ")}\n`);
    return;
  }
  if (mode === "native") {
    await initNativeDevDemo(dataDir);
    process.stdout.write("native dev demo created: demo-anna\n");
    return;
  }
  const served = await serveDevDemo(dataDir, envRelay(resolveReal(resolve(dataDir))));
  const target = resolveReal(resolve(dataDir));
  const ready = join(target, DEV_DEMO_READY);
  const stage = join(target, `${DEV_DEMO_READY}-${process.pid}`);
  writeFileSync(stage, `${process.pid}\n`, { mode: 0o600, flag: "wx" });
  renameSync(stage, ready);
  const stop = () => void served.stop();
  process.once("SIGTERM", stop);
  process.once("SIGINT", stop);
  const code = await served.host.exit;
  await served.stop();
  rmSync(ready, { force: true });
  process.exit(code);
}

/** A native demo's relay from the env (relay/config.ts, checkout rules); invalid or absent: none. */
function envRelay(dataDir: string): { readonly relay?: HostRelayOptions } {
  const loaded = loadRelayConfig({ dataDir, packaged: false, env: process.env });
  if (loaded.kind === "invalid") process.stderr.write(`dev demo: ${loaded.code}\n`);
  if (loaded.kind !== "ready") return {};
  return { relay: { endpoints: loaded.relay, authStore: () => demoRelayAuthStore(dataDir) } };
}

const entry = process.argv[1];
if (entry !== undefined && resolve(entry) === fileURLToPath(import.meta.url)) {
  try {
    await main(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`dev demo: ${error instanceof Error ? error.message : "failed"}\n`);
    process.exit(70);
  }
}
