/**
 * Creates `demo-anna` as a NATIVE vault in `dataDir` (new or empty, under the lab root): the desktop's
 * native Create (`native.creation.prepare` / `commit` over a ui session; the recovery phrase is
 * discarded, synthetic), then `init`'s synthetic seed through durable commands, the price cache and
 * the marker. Keys are the demo's own files (devDemoNative.ts), never the OS keychain.
 */
export async function initNativeDevDemo(
  dataDir: string,
  options: { readonly home?: string; readonly today?: string; readonly labRoot?: string } = {},
): Promise<void> {
  const home = options.home ?? homedir();
  const today = options.today ?? localDay(new Date());
  const target = guardDataDir(insideLab(dataDir, labRoot(options.labRoot)), home);
  if (existsSync(target) && readdirSync(target).length > 0)
    throw new Error("the demo data dir must be new or empty");
  mkdirSync(target, { recursive: true, mode: 0o700 });
  const h = HOUSEHOLDS[0] as Household;
  const start = () =>
    startLocalHost({
      dataDir: target,
      vaultSource: {
        kind: "native-production",
        factory: new ProductionVaultSourceFactory(target, demoKeyStoreFactory(target)),
      },
      home,
      build: BUILD,
      launcher: false,
      ported: [],
    });
  const setup = await start();
  let vault: string;
  try {
    const ui = await connectHost({ dataDir: target, role: "ui", build: BUILD });
    try {
      const prepared = nativeCreationPrepareResultSchema.parse(
        await ui.call("native.creation.prepare", {
          name: h.name,
          slug: h.slug,
          baseCurrency: "PLN",
          modules: [...h.modules],
          mcpPrivacy: "strict",
          deviceAlias: "Demo Mac",
        }),
      );
      if (prepared.kind !== "prepared") throw new Error(`native demo create: ${prepared.code}`);
      const committed = nativeCreationCommitResultSchema.parse(
        await ui.call("native.creation.commit", {
          operationId: prepared.operationId,
          phraseSession: prepared.phraseSession,
        }),
      );
      if (committed.kind !== "ready") throw new Error(`native demo create: ${committed.kind}`);
      vault = committed.vaultId;
    } finally {
      ui.close();
    }
  } finally {
    // A completed Create hands the host over (exit 75); stop joins that.
    await setup.stop();
  }
  const host = await start();
  try {
    const opened = host.stores.vaults.get(vault);
    if (opened?.native === undefined) throw new Error("the native demo vault did not open");
    const rows = await seedBudget(opened, h, today);
    if (h.mortgage) await seedAssetsAndLoan(opened, today, rows.lender);
    if (h.holdings) await seedInvestments(opened, today, marketSeries(today));
    const dir = join(target, "profiles", h.slug);
    mkdirSync(dir, { recursive: true, mode: 0o700 });
    const strategy = demoStrategy();
    writeFileSync(join(dir, "strategy.yaml"), strategy.yaml, { mode: 0o600, flag: "wx" });
    writeFileSync(join(dir, "strategy.md"), strategy.markdown, { mode: 0o600, flag: "wx" });
  } finally {
    await host.stop();
  }
  writeMarketCache(join(target, DEV_DEMO_MARKET_DB), marketSeries(today));
  const marker: Marker = { format: 1, native: true, profiles: [{ slug: h.slug, vault }] };
  writeFileSync(join(target, MARKER), `${JSON.stringify(marker, null, 2)}\n`, {
    mode: 0o600,
    flag: "wx",
  });
}

