/** Weekday series from the first demo month to today: a seeded random walk per instrument / rate. */
function marketSeries(today: string) {
  const rand = prng(0xd3a0);
  const gauss = () => Math.sqrt(-2 * Math.log(1 - rand())) * Math.cos(2 * Math.PI * rand());
  const days: string[] = [];
  for (let day = addDays(monthStarts(today)[0] as string, -10); day <= today; day = addDays(day, 1))
    if (isWeekday(day)) days.push(day);
  const walk = (start: number, drift: number, volatility: number, digits: number) => {
    let level = start;
    return new Map(
      days.map((day) => {
        level *= 1 + drift + volatility * gauss();
        return [day, Number(level.toFixed(digits))] as const;
      }),
    );
  };
  return {
    days,
    bars: new Map(INSTRUMENTS.map((i) => [i.symbol, walk(i.start, i.drift, i.volatility, 2)])),
    rates: new Map(FX.map((r) => [r.currency as string, walk(r.start, 0, r.volatility, 4)])),
  };
}

/** The passive starter adapted to the demo holdings (a single-stock bucket, the demo ETF as proxy). */
function demoStrategy(): { yaml: string; markdown: string } {
  const template = strategyTemplate("passive_etf");
  if (template === null) throw new Error("the passive strategy template is absent");
  const edits: readonly (readonly [string, string])[] = [
    [
      "  - id: cash\n    match: { asset_class: cash }",
      "  - id: stocks\n    match: { asset_class: equity }\n  - id: cash\n    match: { asset_class: cash }",
    ],
    [
      "    global_equity: 0.70\n    bond_etfs: 0.10\n    treasury_bonds: 0.15\n    cash: 0.05",
      "    global_equity: 0.65\n    bond_etfs: 0.15\n    treasury_bonds: 0.05\n    stocks: 0.10\n    cash: 0.05",
    ],
    ["proxy: VWCE.DE", "proxy: DGLB.DE"],
  ];
  let yaml = template.yaml;
  for (const [from, to] of edits) {
    if (!yaml.includes(from)) throw new Error("the passive strategy template changed");
    yaml = yaml.replace(from, to);
  }
  return { yaml, markdown: template.markdown };
}

