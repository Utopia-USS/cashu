/** The EUR account: a few card payments abroad each month, from its own PRNG stream. */
function eurRows(h: Household, today: string): Row[] {
  const rand = prng(h.seed ^ 0xe0e0);
  const rows: Row[] = [];
  for (const month of monthStarts(today))
    for (let i = 0; i < 2; i++) {
      const merchant = rand() < 0.5 ? "KAWIARNIA DEMO WIEN" : "HOTEL DEMO BERLIN";
      rows.push({
        date: onDay(month, between(rand, 1, 28)),
        cents: -between(rand, 1_500, 9_000),
        counterparty: merchant,
        title: merchant,
        description: "ZAKUP PRZY UZYCIU KARTY",
        iban: null,
      });
    }
  return rows.filter((r) => r.date <= today).sort((a, b) => a.date.localeCompare(b.date));
}

function statement(
  iban: string,
  name: string,
  opening: number,
  rows: readonly Row[],
  tag: string,
  currency: "PLN" | "EUR" = "PLN",
) {
  let balance = opening;
  const transactions: RawTransaction[] = [];
  const balances: { date: string; amount: ReturnType<typeof D> }[] = [];
  for (const [index, row] of rows.entries()) {
    balance += row.cents;
    transactions.push({
      bookingDate: row.date,
      valueDate: row.date,
      amount: D(money(row.cents)),
      currency,
      counterpartyName: row.counterparty || null,
      counterpartyIban: row.iban,
      description: row.description,
      reference: row.title,
      bankTransactionId: `DEMO-${tag}-${index + 1}`,
      source: "csv",
      raw: { row: index + 1 },
    });
    balances.push({ date: row.date, amount: D(money(balance)) });
  }
  return {
    bank: "mbank",
    accountNumber: iban,
    accountName: name,
    currency,
    transactions,
    balances,
    closingBalances: [],
  };
}

