/** mulberry32: a small deterministic PRNG. */
function prng(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const between = (rand: () => number, low: number, high: number) =>
  Math.round(low + rand() * (high - low));
const pad = (n: number) => String(n).padStart(2, "0");
const localDay = (d: Date) => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
const dayOf = (iso: string) => new Date(`${iso}T12:00:00`);
const addDays = (iso: string, days: number) => {
  const d = dayOf(iso);
  d.setDate(d.getDate() + days);
  return localDay(d);
};
const isWeekday = (iso: string) => {
  const w = dayOf(iso).getDay();
  return w !== 0 && w !== 6;
};
/** The same day, or the next weekday. */
const weekdayFrom = (iso: string) => {
  let day = iso;
  while (!isWeekday(day)) day = addDays(day, 1);
  return day;
};
/** Grosze as decimal text. */
const money = (cents: number) =>
  `${cents < 0 ? "-" : ""}${Math.floor(Math.abs(cents) / 100)}.${pad(Math.abs(cents) % 100)}`;

/** A Polish IBAN with a valid checksum around an obviously fake, mostly zero account number. */
function fakeIban(bank: string, account: number): string {
  const bban = `${bank.padEnd(8, "0")}${String(account).padStart(16, "0")}`;
  const check = 98n - (BigInt(`${bban}252100`) % 97n);
  return `PL${String(check).padStart(2, "0")}${bban}`;
}

/** The first day of each of the last `MONTHS` months and the current one, oldest first. */
function monthStarts(today: string): string[] {
  const now = dayOf(today);
  return Array.from({ length: MONTHS + 1 }, (_, i) =>
    localDay(new Date(now.getFullYear(), now.getMonth() - MONTHS + i, 1)),
  );
}
const onDay = (monthStart: string, day: number) => `${monthStart.slice(0, 8)}${pad(day)}`;

